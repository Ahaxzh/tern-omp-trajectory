#!/usr/bin/env bash
# Regenerates tests/fixtures.luau from real omp session logs on this machine.
# The two source files and the ground-truth numbers in tests/run.luau were
# measured on 2026-10-20; if you regenerate against different sessions,
# update the expected counts in run.luau to match (jq one-liners in the
# delivery report show how).
set -euo pipefail
cd "$(dirname "$0")"

A="${A:-$HOME/.omp/agent/sessions/-Projects-GitHub-Blog/2026-10-19T07-01-29-777Z_01a152f7-2031-77dd-b6bb-d79b7071a7a0.jsonl}"
B="${B:-$HOME/.omp/agent/sessions/-Projects-GitHub/2026-10-20T02-18-27-378Z_01a1571a-5ab2-7044-9e8f-0d7c00abb5cc.jsonl}"

[ -r "$A" ] || { echo "missing $A" >&2; exit 1; }
[ -r "$B" ] || { echo "missing $B" >&2; exit 1; }

python3 - "$A" "$B" > fixtures.luau <<'PY'
import json, os, sys

def lua_str(b: bytes) -> str:
    out = ['"']
    for byte in b:
        c = chr(byte)
        if c == '"': out.append('\\"')
        elif c == '\\': out.append('\\\\')
        elif c == '\n': out.append('\\n')
        elif c == '\r': out.append('\\r')
        elif 32 <= byte < 127: out.append(c)
        else: out.append('\\%03d' % byte)
    out.append('"')
    return ''.join(out)

parts = [
    "--!strict",
    "-- Generated by tests/gen_fixtures.sh from real omp session logs on this machine.",
    "-- Regenerate after changing the source sessions. Do not edit by hand.",
    "local Fixtures = {}",
    "",
]
for key, path in zip(("A", "B"), sys.argv[1:3]):
    data = open(path, "rb").read()
    parts.append(f"Fixtures.{key}_name = {json.dumps(os.path.basename(path))}")
    parts.append(f"Fixtures.{key}_text = {lua_str(data)}")
    parts.append("")
parts.append("return Fixtures")
sys.stdout.write("\n".join(parts) + "\n")
PY

echo "wrote fixtures.luau ($(wc -c < fixtures.luau) bytes)"
